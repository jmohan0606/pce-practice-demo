def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--cohort", default="data/real/cohort.txt")
    ap.add_argument("--out", default="docs/data/extraction")
    args = ap.parse_args()

    cohort_path = Path(args.cohort)
    if not cohort_path.exists():
        print(f"ERROR: {cohort_path} not found — write one advisor_sid per line "
              f"(the full book from the sizing query)", file=sys.stderr)
        return 1
    sids = [ln.strip() for ln in cohort_path.read_text(encoding="utf-8").splitlines()
            if ln.strip() and not ln.startswith("#")]
    if not sids:
        print(f"ERROR: {cohort_path} contains no advisor SIDs", file=sys.stderr)
        return 1
    print(f"cohort: {len(sids)} advisors from {cohort_path}")

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "00_session_setup.sql").write_text(
        session_setup_sql(sids, str(cohort_path)), encoding="utf-8")
    print(f"wrote {out / '00_session_setup.sql'}")
    for fname, body in templates(sids).items():
        csv_name = fname.replace(".sql", ".csv")
        text = HEADER.format(cohort_path=cohort_path, csv_name=csv_name) + body.lstrip("\n")
        (out / fname).write_text(text, encoding="utf-8")
        print(f"wrote {out / fname}")
    for month_id in BALANCE_TABLES:
        fname = f"raw_balance_{month_id}.sql"
        text = HEADER.format(cohort_path=cohort_path,
                             csv_name=f"raw_balance_{month_id}.csv") \
            + monthly_balance_sql(month_id).lstrip("\n")
        (out / fname).write_text(text, encoding="utf-8")
