"""Round F task 4.2 / Round 2a task 2 — write docs/data/extraction/*.sql.

    python3 scripts/generate_extraction_sql.py [--cohort data/real/cohort.txt]
                                               [--out docs/data/extraction]

Round 2a: the cohort is the FIRM (5,746 advisors) and the in-scope account set
is ~3M keys — NEITHER is ever inlined into an IN (...) list. Every session
starts with 00_session_setup.sql, which creates two TEMP tables:

  cohort_adv (advisor_sid)  — loaded from cohort.txt
  scoped_acct (k)           — every in-scope traded account key, computed ONCE
                              per session instead of re-scanning the 12.4M-row
                              trade table once per extract

and every template joins them. A temp table does NOT survive a reconnect, and
a token refresh IS a reconnect — scripts/extract_chunked.py re-runs the setup
on every connection automatically; a human running the .sql files by hand must
re-run 00_session_setup.sql after any reconnect.

The three account-scoped multi-million-row tables (raw_account,
raw_acct_eci_rel, raw_acct_eci_map) carry a /*BUCKET*/ marker where
extract_chunked.py injects `AND mod(abs(hashtext(s.k)), :n) = :b` to split
them into deterministic, resumable bucket chunks. raw_monthly_balance is
split BY MONTH (one query per month table — never one UNION).

Corrections baked in (ROUND_D_EXTRACTION.md §4, client-confirmed):
  - raw_acct_eci_map: source column IS new_exst_adv_clnt_in_cyr (no rename in SQL —
    build_real_data.py maps it to the graph's new_exst_adv_clnt_in);
    latest bus_dt per (wm_src_sys_cd, wm_acct_src_nb) only.
  - raw_monthly_balance: columns are acct_id, acct_bal (per-month files).
  - raw_advisor: includes transfer counterparties outside the cohort with
    in_cohort=false (or every transfer edge pointing at them drops at load).
  - raw_adv_flows: APRIL-JUNE (Round 2a: June flow rows now exist — 19,443,868
    daily rows across the three months aggregate to 166,985 output rows; the
    aggregate is what extracts, never the daily rows); other_attributes JSONB
    flattened into the six named columns.
  - raw_advisor_flags (Round 5 task 1): RETIRED — it existed only to score
    advisors for scripts/select_cohort.py's 20-advisor demo selection, and the
    client now DEFINES the cohort (scripts/build_cohort.py runs their query);
    nothing selects anything and nothing consumes the file.
  - cohort application (Round 5 task 1, client-mandated): the cohort is
    applied via ``advisor_sid IN (SELECT advisor_sid FROM cohort_adv)`` —
    NEVER a join. fpic_prm_rr_tb / fpic_employee_tb are reference tables with
    one row per branch/location; joining them to the trade table both drops
    unmatched rows and multiplies matched ones (the 4.1M-row loss).
  - month meta: expect 30/31/30 calendar days (the table accrues daily).
"""
