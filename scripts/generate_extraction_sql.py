# Round 5 task 1: the ONE cohort-application line every scoped extract uses —
# IN (SELECT ...), NEVER a join (client-mandated; reference tables carry one
# row per branch/location, so a join fans out / drops rows — the 4.1M loss).
# extract_chunked.txn_chunk_sql swaps this exact line for a per-chunk batch.
TXN_COHORT_LINE = "  AND  d.advisor_sid IN (SELECT advisor_sid FROM cohort_adv)\n"

# Templates that carry the /*BUCKET*/ marker — extract_chunked.py splits each
# into --buckets deterministic chunks over scoped_acct's key hash.
BUCKETED_SQL = ("raw_account.sql", "raw_acct_eci_rel.sql", "raw_acct_eci_map.sql")

# The marker extract_chunked.py replaces. Kept as a constant so the assertion
# there and the templates here cannot drift apart.
BUCKET_MARKER = "/*BUCKET*/"


def bucket_predicate(n_buckets: int, bucket: int) -> str:
    """The deterministic, reproducible bucket split over the scoped account
    key. hashtext() is stable within a PostgreSQL major version, which is all
    a resumable extract needs (all buckets of a table come from one plan)."""
    return f"AND mod(abs(hashtext(s.k)), {n_buckets}) = {bucket}"


def session_setup_statements(sids: list[str]) -> list[str]:
    """The per-session temp-table setup as individual executable statements.
    cohort_adv is loaded by multi-row INSERTs (500 SIDs per statement — never
    one giant literal); scoped_acct is computed ONCE from the trade table."""
    stmts = ["CREATE TEMP TABLE cohort_adv (advisor_sid varchar(11) PRIMARY KEY)"]
    for i in range(0, len(sids), 500):
        values = ",".join(f"('{s}')" for s in sids[i:i + 500])
        stmts.append(f"INSERT INTO cohort_adv (advisor_sid) VALUES {values}")
    stmts.append(f"""CREATE TEMP TABLE scoped_acct AS
SELECT DISTINCT ltrim(trim(d.account_no),'0') AS k
FROM   pcr.fpic_daily_trade_details_tb_prod d
WHERE  d.trade_dt >= DATE '{SCOPE_START}' AND d.trade_dt < DATE '{SCOPE_END}'
  AND  d.advisor_sid IN (SELECT advisor_sid FROM cohort_adv)""")
    stmts.append("CREATE INDEX ON scoped_acct (k)")
    stmts.append("ANALYZE scoped_acct")
    return stmts


def session_setup_sql(sids: list[str], cohort_path: str = "data/real/cohort.txt") -> str:
    """00_session_setup.sql for a human session. States the reconnect rule."""
    return (
        "-- 00_session_setup.sql — run at the START of EVERY database session,\n"
        "-- BEFORE any extract. A temp table does not survive a reconnect, and a\n"
        "-- token refresh IS a reconnect: after any re-auth, run this again.\n"
        f"-- (psql alternative for cohort_adv: \\copy cohort_adv FROM '{cohort_path}')\n"
        "SET statement_timeout = '600s';\n\n"
        + ";\n\n".join(session_setup_statements(sids)) + ";\n"
    )


def monthly_balance_sql(month_id: str) -> str:
    """One month's balance extract — its own query, its own CSV
    (raw_balance_<month>.csv). Joins scoped_acct; never a UNION."""
    table = BALANCE_TABLES.get(month_id)
    if table is None:
        raise KeyError(
            f"no balance table known for month {month_id} — extend "
            f"BALANCE_TABLES in scripts/generate_extraction_sql.py (known: "
            f"{sorted(BALANCE_TABLES)})")
    return f"""
-- Month-end balances for {month_id}: columns confirmed acct_id / acct_bal.
-- ONE month per query (never a UNION — 8.68M rows in one statement will not
-- finish inside the 900s timeout). Requires 00_session_setup.sql this session.
SELECT '{month_id}' AS month_id, b.acct_id, b.acct_bal
FROM   pcr.{table} b
JOIN   scoped_acct s ON s.k = ltrim(trim(b.acct_id),'0');
"""


